const MOBILE_TOUCH_QUERY = '(max-width: 900px) and (pointer: coarse)';
const LONG_PRESS_MS = 550;
const CANCEL_DISTANCE_PX = 10;

let activePress = null;
const allowedClicks = new WeakSet();

function isMobileTouchPlanner() {
  return window.matchMedia(MOBILE_TOUCH_QUERY).matches;
}

function timelineEventFromTarget(target) {
  return target?.closest?.('.planner-timeline-event[data-event-id]') || null;
}

function clearActivePress() {
  if (!activePress) return;
  window.clearTimeout(activePress.timer);
  activePress.element.classList.remove('tpos-long-press-pending');
  activePress = null;
}

function cancelForMovement(event) {
  if (!activePress || event.pointerId !== activePress.pointerId) return;

  const distance = Math.hypot(
    event.clientX - activePress.startX,
    event.clientY - activePress.startY,
  );

  if (distance > CANCEL_DISTANCE_PX) {
    clearActivePress();
  }
}

function installLongPressEditing() {
  document.addEventListener('pointerdown', event => {
    if (!isMobileTouchPlanner()) return;

    const element = timelineEventFromTarget(event.target);
    if (!element) return;

    // The Calendar component normally starts drag/resize from pointerdown.
    // On touch devices we stop that event before it reaches the component,
    // while leaving the browser's native scrolling untouched.
    event.stopImmediatePropagation();

    clearActivePress();

    const pointerId = event.pointerId;
    const startX = event.clientX;
    const startY = event.clientY;

    const timer = window.setTimeout(() => {
      if (!activePress || activePress.pointerId !== pointerId) return;

      element.classList.remove('tpos-long-press-pending');
      allowedClicks.add(element);

      // Reuse the Calendar's existing click handler to open the edit dialog.
      // The later real tap/click generated by pointerup is still suppressed.
      element.click();
      activePress = null;
    }, LONG_PRESS_MS);

    activePress = {
      element,
      pointerId,
      startX,
      startY,
      timer,
    };

    element.classList.add('tpos-long-press-pending');
  }, true);

  document.addEventListener('pointermove', cancelForMovement, true);

  document.addEventListener('pointerup', event => {
    if (!activePress || event.pointerId !== activePress.pointerId) return;
    clearActivePress();
  }, true);

  document.addEventListener('pointercancel', event => {
    if (!activePress || event.pointerId !== activePress.pointerId) return;
    clearActivePress();
  }, true);

  document.addEventListener('click', event => {
    if (!isMobileTouchPlanner()) return;

    const element = timelineEventFromTarget(event.target);

    if (element) {
      if (allowedClicks.has(element)) {
        allowedClicks.delete(element);
        return;
      }

      // Preserve keyboard/accessibility activation where available.
      if (event.detail === 0) return;

      // A normal tap must never open or mutate an event on mobile.
      event.preventDefault();
      event.stopImmediatePropagation();
      return;
    }

    const blankTimelineDay = event.target?.closest?.('.planner-timeline-day');
    if (blankTimelineDay) {
      // Creating an event by tapping an empty time slot is disabled on touch.
      // The explicit + buttons remain the only creation gesture.
      event.preventDefault();
      event.stopImmediatePropagation();
    }
  }, true);

  document.addEventListener('contextmenu', event => {
    if (!isMobileTouchPlanner()) return;
    if (!timelineEventFromTarget(event.target)) return;

    event.preventDefault();
    event.stopImmediatePropagation();
  }, true);
}

function ensureMobileHint() {
  if (!isMobileTouchPlanner()) return;

  const timeline = document.querySelector('.planner-timeline-scroll');
  if (!timeline || document.querySelector('[data-mobile-calendar-hint]')) return;

  const hint = document.createElement('div');
  hint.className = 'planner-mobile-touch-hint';
  hint.dataset.mobileCalendarHint = 'true';
  hint.innerHTML = `
    <span aria-hidden="true">☝️</span>
    <span><strong>Su touch:</strong> tieni premuta un’attività per modificarla. Usa <strong>+</strong> per crearne una nuova.</span>
  `;

  timeline.insertAdjacentElement('beforebegin', hint);
}

installLongPressEditing();

const observer = new MutationObserver(() => {
  window.queueMicrotask(ensureMobileHint);
});

observer.observe(document.body, {
  childList: true,
  subtree: true,
});

window.addEventListener('hashchange', () => {
  clearActivePress();
  window.queueMicrotask(ensureMobileHint);
});

window.addEventListener('blur', clearActivePress);
document.addEventListener('visibilitychange', () => {
  if (document.hidden) clearActivePress();
});

window.queueMicrotask(ensureMobileHint);
